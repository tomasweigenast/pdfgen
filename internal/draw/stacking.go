package draw

import (
	"slices"

	"github.com/tomasweigenast/pdfgen/internal/boxes"
)

// StackingContext orders the painting of the boxes of a page (CSS 2.1
// Appendix E). Its fields are the lists of the painting order, from step 3 on.
type StackingContext struct {
	// Box is the box that generates the context, without the boxes that
	// were moved to the other fields.
	Box  boxes.Box
	Page *boxes.PageBox
	// ZIndex is the z-index of the box; auto counts as 0.
	ZIndex int

	// BlockLevelBoxes are the in-flow, non-positioned block-level
	// descendants, in tree order (step 4).
	BlockLevelBoxes []boxes.Box
	// FloatContexts are the contexts of the non-positioned floats (step 5).
	FloatContexts []*StackingContext
	// BlocksAndCells is the tree of block-level boxes and table cells whose
	// inline content is painted in step 7.
	BlocksAndCells []BlockEntry

	NegativeZ []*StackingContext // step 3, by increasing z-index
	ZeroZ     []*StackingContext // step 8, in tree order
	PositiveZ []*StackingContext // step 9, by increasing z-index
}

// BlockEntry is a block-level box or a table cell with the entries of the
// blocks and cells nested in it.
type BlockEntry struct {
	Box      boxes.Box
	Children []BlockEntry
}

// contextBox takes the place of an inline-level box that is a stacking
// context in the children of its parent, so that it is painted where it sits
// among the inline content.
type contextBox struct {
	boxes.Box
	context *StackingContext
}

// FromPage returns the stacking context of a page. The root element box and
// the margin boxes are contexts of their own.
func FromPage(page *boxes.PageBox) *StackingContext {
	children := make([]*StackingContext, 0, len(page.Children))
	for _, child := range page.Children {
		children = append(children, FromBox(child, page))
	}
	stripped := page.CopyWithChildren(nil).(*boxes.PageBox)
	return newContext(stripped, children, nil, nil, nil, stripped)
}

// FromBox returns the stacking context generated by box.
func FromBox(box boxes.Box, page *boxes.PageBox) *StackingContext {
	return fromBox(box, page, nil)
}

// fromBox builds the context of box. The contexts of the stacking descendants
// are added to parentContexts when it is not nil, which makes box a context
// "as if" it created one: its positioned descendants and the descendants that
// create a context belong to the parent context (CSS 2.1 Appendix E).
func fromBox(box boxes.Box, page *boxes.PageBox, parentContexts *[]*StackingContext) *StackingContext {
	var own []*StackingContext
	contexts := parentContexts
	if contexts == nil {
		contexts = &own
	}
	var blocks []boxes.Box
	var floats []*StackingContext
	var cells []BlockEntry
	d := dispatcher{page: page, contexts: contexts, blocks: &blocks, floats: &floats}
	box = d.children(box, &cells)
	return newContext(box, own, blocks, floats, cells, page)
}

func newContext(box boxes.Box, children []*StackingContext, blocks []boxes.Box,
	floats []*StackingContext, cells []BlockEntry, page *boxes.PageBox) *StackingContext {
	c := &StackingContext{
		Box:             box,
		Page:            page,
		BlockLevelBoxes: blocks,
		FloatContexts:   floats,
		BlocksAndCells:  cells,
	}
	if z := box.Base().Style.ZIndex(); z.Keyword != "auto" {
		c.ZIndex = z.N
	}
	for _, child := range children {
		switch {
		case child.ZIndex < 0:
			c.NegativeZ = append(c.NegativeZ, child)
		case child.ZIndex == 0:
			c.ZeroZ = append(c.ZeroZ, child)
		default:
			c.PositiveZ = append(c.PositiveZ, child)
		}
	}
	byZIndex := func(a, b *StackingContext) int { return a.ZIndex - b.ZIndex }
	slices.SortStableFunc(c.NegativeZ, byZIndex)
	slices.SortStableFunc(c.PositiveZ, byZIndex)
	return c
}

// dispatcher sorts the descendants of a box into the lists of a stacking
// context.
type dispatcher struct {
	page     *boxes.PageBox
	contexts *[]*StackingContext
	blocks   *[]boxes.Box
	floats   *[]*StackingContext
}

// dispatch returns the box to keep in the children of its parent, or nil
// when it was moved to a stacking context.
func (d dispatcher) dispatch(box boxes.Box, cells *[]BlockEntry) boxes.Box {
	if p, ok := box.(*boxes.AbsolutePlaceholder); ok {
		box = p.Box
	}
	style := box.Base().Style

	positioned := style.Position().Keyword != "static"
	zAuto := style.ZIndex().Keyword == "auto"
	if (positioned && !zAuto) ||
		(box.Base().IsGridItem && !zAuto) ||
		style.Opacity() < 1 ||
		len(style.Transform()) > 0 ||
		style.Overflow() != "visible" {
		*d.contexts = append(*d.contexts, FromBox(box, d.page))
		return nil
	}

	switch {
	case positioned:
		// A positioned box with z-index: auto is painted as if it created a
		// context, but the contexts below it belong to the parent. It goes
		// in the list before them.
		index := len(*d.contexts)
		context := fromBox(box, d.page, d.contexts)
		*d.contexts = slices.Insert(*d.contexts, index, context)
		return nil
	case box.IsFloated():
		*d.floats = append(*d.floats, fromBox(box, d.page, d.contexts))
		return nil
	}

	switch box.Kind() {
	case boxes.KindInlineBlock, boxes.KindInlineFlex, boxes.KindInlineGrid:
		// The context stays in the tree of inline boxes, because it is
		// painted in the middle of them.
		context := fromBox(box, d.page, d.contexts)
		return &contextBox{Box: context.Box, context: context}
	case boxes.KindTableCell:
		var nested []BlockEntry
		box = d.children(box, &nested)
		*cells = append(*cells, BlockEntry{Box: box, Children: nested})
		return box
	}

	if _, ok := box.(boxes.BlockLevel); ok {
		index := len(*d.blocks)
		var nested []BlockEntry
		box = d.children(box, &nested)
		// The box comes before the blocks found in its children.
		*d.blocks = slices.Insert(*d.blocks, index, box)
		*cells = append(*cells, BlockEntry{Box: box, Children: nested})
		return box
	}
	return d.children(box, cells)
}

// children dispatches the children of box and returns a copy of box that
// holds the ones that remain.
func (d dispatcher) children(box boxes.Box, cells *[]BlockEntry) boxes.Box {
	parent, ok := box.(boxes.Parent)
	if !ok {
		return box
	}
	children := parent.ParentBase().Children
	kept := make([]boxes.Box, 0, len(children))
	for _, child := range children {
		if result := d.dispatch(child, cells); result != nil {
			kept = append(kept, result)
		}
	}
	return parent.CopyWithChildren(kept)
}
