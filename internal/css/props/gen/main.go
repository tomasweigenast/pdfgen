// Command gen writes props_gen.go and the typed style getters from the
// property table. It is run by go generate from internal/css/props.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"

	"github.com/tomasweigenast/pdfgen/internal/css/props"
)

const header = "// Code generated by go generate; DO NOT EDIT.\n\n"

var check = flag.Bool("check", false, "report stale generated files instead of writing them")

func main() {
	flag.Parse()
	log.SetFlags(0)
	log.SetPrefix("gen: ")
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	if err := checkTable(props.Table); err != nil {
		return err
	}
	if err := write("props_gen.go", propsSource(props.Table)); err != nil {
		return err
	}
	return write(filepath.Join("..", "computed", "style_gen.go"), styleSource(props.Table))
}

func checkTable(table []props.PropInfo) error {
	seen := map[string]bool{}
	for _, p := range table {
		if p.Initial == nil {
			return fmt.Errorf("property %q has no initial value", p.Name)
		}
		if seen[p.Name] {
			return fmt.Errorf("property %q is listed twice", p.Name)
		}
		seen[p.Name] = true
	}
	return nil
}

func write(path string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("formatting %s: %w\n%s", path, err, src)
	}
	if *check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, formatted) {
			return fmt.Errorf("%s is out of date", path)
		}
		return nil
	}
	return os.WriteFile(path, formatted, 0o644)
}

// goName converts a CSS property name to an exported Go identifier part.
func goName(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "-") {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

func propsSource(table []props.PropInfo) []byte {
	var b bytes.Buffer
	b.WriteString("package props\n\n")

	b.WriteString("// Property identifiers, in table order.\nconst (\n")
	for i, p := range table {
		if i == 0 {
			fmt.Fprintf(&b, "\tProp%s PropID = iota\n", goName(p.Name))
		} else {
			fmt.Fprintf(&b, "\tProp%s\n", goName(p.Name))
		}
	}
	b.WriteString(")\n\n")

	b.WriteString(lookups)
	b.WriteString("var propNames = [...]string{\n")
	for _, p := range table {
		fmt.Fprintf(&b, "\t%q,\n", p.Name)
	}
	b.WriteString("}\n\nvar idByName = map[string]PropID{\n")
	for _, p := range table {
		fmt.Fprintf(&b, "\t%q: Prop%s,\n", p.Name, goName(p.Name))
	}
	b.WriteString("}\n\n")

	bits := func(name string, pick func(props.PropInfo) bool) {
		words := make([]uint64, (len(table)+63)/64)
		for i, p := range table {
			if pick(p) {
				words[i/64] |= 1 << (i % 64)
			}
		}
		fmt.Fprintf(&b, "var %s = bitset{", name)
		for i, w := range words {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%#x", w)
		}
		b.WriteString("}\n\n")
	}
	bits("inheritedBits", func(p props.PropInfo) bool { return p.Inherited })
	bits("initialNotComputedBits", func(p props.PropInfo) bool { return p.InitialNotComputed })
	bits("tableWrapperBits", func(p props.PropInfo) bool { return p.TableWrapper })

	b.WriteString("var initialValues = [...]Value{\n")
	for _, p := range table {
		fmt.Fprintf(&b, "\tProp%s: %s,\n", goName(p.Name), literal(reflect.ValueOf(p.Initial)))
	}
	b.WriteString("}\n")

	body := b.String()
	var out bytes.Buffer
	out.WriteString(header)
	out.WriteString("package props\n\n")
	var std []string
	if strings.Contains(body, "math.") {
		std = append(std, "\t\"math\"\n")
	}
	std = append(std, "\t\"strings\"\n")
	out.WriteString("import (\n" + strings.Join(std, ""))
	if strings.Contains(body, "syntax.") {
		out.WriteString("\n\t\"github.com/tomasweigenast/pdfgen/internal/css/syntax\"\n")
	}
	out.WriteString(")\n\n")
	out.WriteString(strings.TrimPrefix(body, "package props\n\n"))
	return out.Bytes()
}

const lookups = `// ID returns the identifier of the property with the given name. Names are
// matched case-insensitively.
func ID(name string) (PropID, bool) {
	id, ok := idByName[strings.ToLower(name)]
	return id, ok
}

// Name returns the CSS name of the property.
func (id PropID) Name() string { return propNames[id] }

// Info returns the table entry of the property.
func (id PropID) Info() *PropInfo { return &Table[id] }

// Inherited reports whether the property is inherited by default.
func (id PropID) Inherited() bool { return inheritedBits.has(id) }

// InitialNotComputed reports whether the initial value of the property has to
// be computed before use.
func (id PropID) InitialNotComputed() bool { return initialNotComputedBits.has(id) }

// TableWrapper reports whether the property applies to the wrapper box of a
// table.
func (id PropID) TableWrapper() bool { return tableWrapperBits.has(id) }

// Initial returns the initial value of the property.
func (id PropID) Initial() Value { return initialValues[id] }

// NumProps is the number of properties.
func NumProps() int { return len(propNames) }

`

func styleSource(table []props.PropInfo) []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package computed\n\nimport \"github.com/tomasweigenast/pdfgen/internal/css/props\"\n\n")
	for _, p := range table {
		name := goName(p.Name)
		t := reflect.TypeOf(p.Initial).Name()
		fmt.Fprintf(&b, "// %s returns the value of the %s property.\n", name, p.Name)
		fmt.Fprintf(&b, "func (s *Style) %s() props.%s { return get[props.%s](s, props.Prop%s) }\n\n", name, t, t, name)
	}
	return b.Bytes()
}

// literal returns Go source for v, as written in package props.
func literal(v reflect.Value) string { return lit(v, false) }

// lit writes v; with elided set the type of v is left out, as allowed for the
// elements of slice and array literals.
func lit(v reflect.Value, elided bool) string {
	t := v.Type()
	basic := func(src string) string {
		if elided || t.PkgPath() == "" {
			return src
		}
		return typeName(t) + "(" + src + ")"
	}
	switch t.Kind() {
	case reflect.String:
		return basic(strconv.Quote(v.String()))
	case reflect.Bool:
		return strconv.FormatBool(v.Bool())
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return basic(strconv.FormatInt(v.Int(), 10))
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return basic(strconv.FormatUint(v.Uint(), 10))
	case reflect.Float32, reflect.Float64:
		f := v.Float()
		switch {
		case math.IsInf(f, 1):
			return basic("math.Inf(1)")
		case math.IsInf(f, -1):
			return basic("math.Inf(-1)")
		case math.IsNaN(f):
			return basic("math.NaN()")
		}
		return basic(strconv.FormatFloat(f, 'g', -1, 64))
	case reflect.Struct:
		var fields []string
		for i := 0; i < t.NumField(); i++ {
			if !v.Field(i).IsZero() {
				fields = append(fields, t.Field(i).Name+": "+lit(v.Field(i), false))
			}
		}
		name := typeName(t)
		if elided {
			name = ""
		}
		return name + "{" + strings.Join(fields, ", ") + "}"
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && v.IsNil() {
			return typeName(t) + "(nil)"
		}
		elems := make([]string, v.Len())
		for i := range elems {
			elems[i] = lit(v.Index(i), true)
		}
		name := typeName(t)
		if elided {
			name = ""
		}
		return name + "{" + strings.Join(elems, ", ") + "}"
	}
	panic(fmt.Sprintf("gen: cannot print a value of type %s", t))
}

// typeName returns the name of t as written in package props.
func typeName(t reflect.Type) string {
	switch {
	case t.PkgPath() == propsPath:
		return t.Name()
	case t.Name() != "":
		return t.String()
	case t.Kind() == reflect.Slice:
		return "[]" + typeName(t.Elem())
	case t.Kind() == reflect.Array:
		return fmt.Sprintf("[%d]%s", t.Len(), typeName(t.Elem()))
	}
	return t.String()
}

var propsPath = reflect.TypeOf(props.PropInfo{}).PkgPath()
