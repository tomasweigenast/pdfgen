package boxes

import (
	"regexp"
	"strings"
	"unicode"

	"github.com/tomasweigenast/pdfgen/internal/text/transform"
)

// isSpace reports whether r is white space as defined by Unicode, which
// also includes the information separators U+001C to U+001F.
func isSpace(r rune) bool {
	return unicode.IsSpace(r) || (0x1c <= r && r <= 0x1f)
}

var (
	lineFeedRE  = regexp.MustCompile(`\r\n?`)
	lineBreakRE = regexp.MustCompile(`[\t ]*\n[\t ]*`)
	spaceRE     = regexp.MustCompile(`[\t ]+`)
)

// ProcessWhitespace applies the first part of the white-space processing
// model to the text of a box and its descendants (CSS Text 3 §4.1, CSS 2.1
// §16.6.1). It takes and returns whether the text before the box ends with a
// collapsible space.
func ProcessWhitespace(b Box, followingCollapsibleSpace bool) bool {
	if t, ok := b.(*TextBox); ok {
		return t.ProcessWhitespace(followingCollapsibleSpace)
	}
	for _, child := range ChildrenOf(b) {
		collapsible := ProcessWhitespace(child, followingCollapsibleSpace)
		switch child.Kind() {
		case KindText, KindInline:
			followingCollapsibleSpace = collapsible
		default:
			if child.IsInNormalFlow() {
				followingCollapsibleSpace = false
			}
		}
	}
	return followingCollapsibleSpace
}

// ProcessWhitespace collapses the white space of the text according to the
// white-space property and tells whether the text ends with a collapsible
// space. A collapsible space removed at the start is recorded in
// LeadingCollapsibleSpace.
func (t *TextBox) ProcessWhitespace(followingCollapsibleSpace bool) bool {
	text := t.Text
	if text == "" {
		return followingCollapsibleSpace
	}
	text = lineFeedRE.ReplaceAllString(text, "\n")

	ws := t.Style.WhiteSpace()
	newLineCollapse := ws == "normal" || ws == "nowrap"
	spaceCollapse := newLineCollapse || ws == "pre-line"

	if spaceCollapse {
		text = lineBreakRE.ReplaceAllString(text, "\n")
	}
	if newLineCollapse {
		text = strings.ReplaceAll(text, "\n", " ")
	}
	if spaceCollapse {
		text = spaceRE.ReplaceAllString(text, " ")
		endsWithSpace := strings.HasSuffix(text, " ")
		if followingCollapsibleSpace && strings.HasPrefix(text, " ") {
			text = text[1:]
			t.LeadingCollapsibleSpace = true
		}
		followingCollapsibleSpace = endsWithSpace
	} else {
		followingCollapsibleSpace = false
	}
	t.Text = text
	return followingCollapsibleSpace
}

// IsWhitespace reports whether a box is a text box with only white space.
func IsWhitespace(b Box) bool {
	t, ok := b.(*TextBox)
	return ok && strings.TrimFunc(t.Text, isSpace) == ""
}

// ProcessTextTransform applies text-transform and hyphens: none to the
// text of a box and its descendants. Running elements, footnotes and notes
// are not transformed: they are when they are placed.
func ProcessTextTransform(b Box) {
	if t, ok := b.(*TextBox); ok {
		t.processTextTransform()
		return
	}
	base := b.Base()
	if base.IsRunning() || base.IsFootnote() || base.IsNote() {
		return
	}
	for _, child := range ChildrenOf(b) {
		ProcessTextTransform(child)
	}
}

func (t *TextBox) processTextTransform() {
	if tt := string(t.Style.TextTransform()); tt != "none" {
		lang, _, _ := strings.Cut(string(t.Style.Lang()), "-")
		t.Text, _ = transform.Transform(tt, t.Text, strings.ToLower(lang))
	}
	if t.Style.Hyphens() == "none" {
		t.Text = strings.ReplaceAll(t.Text, "\u00ad", "")
	}
}

// ContentText returns the text of a box as its content: the text of the
// descendants with white space processed, without generated content, and
// stripped. Boxes without text give an empty string.
func ContentText(b Box) string {
	switch b.(type) {
	case *TextBox:
		c := b.DeepCopy().(*TextBox)
		c.ProcessWhitespace(false)
		return strings.TrimFunc(c.Text, isSpace)
	case Parent:
	default:
		return ""
	}
	c := b.DeepCopy()
	ProcessWhitespace(c, false)
	var out strings.Builder
	for d := range Descendants(c, false) {
		t, ok := d.(*TextBox)
		if !ok {
			continue
		}
		tag := t.ElementTag
		if strings.HasSuffix(tag, "::before") || strings.HasSuffix(tag, "::after") || strings.HasSuffix(tag, "::marker") {
			continue
		}
		out.WriteString(t.Text)
	}
	return strings.TrimFunc(out.String(), isSpace)
}

// ExtractText returns a part of the text of a box: "text" or "content" for
// its content text, "before" or "after" for the text generated by those
// pseudo-elements, and "first-letter" for the first letter of the content.
// Other parts give an empty string.
func ExtractText(b Box, part string) string {
	switch part {
	case "text", "content":
		return ContentText(b)
	case "before", "after":
		var out strings.Builder
		for d := range Descendants(b, false) {
			if !strings.HasSuffix(d.Base().ElementTag, "::"+part) {
				continue
			}
			if _, isParent := d.(Parent); !isParent {
				out.WriteString(ContentText(d))
			}
		}
		return out.String()
	case "first-letter":
		return transform.FirstLetter(ContentText(b))
	}
	return ""
}
